// 판매정보 탭 콘텐츠(취소·환불 규정). 공연별 데이터가 아니라 정적 문구 —
// SCREENS.md 판매정보 콘텐츠 기준. 공연장소·관람등급만 공연 값으로 채운다.
export function buildSalesInfo(opts: { venueName: string; ageLimit: string | null }): string {
  const { venueName, ageLimit } = opts;
  return `## 상품 기본정보

- **주최/기획** (주)티케팅랩
- **고객문의** 1600-0000
- **공연장소** ${venueName}
- **관람등급** ${ageLimit ?? '전체 관람가'}
- **예매수수료** 장당 2,000원
- **배송료** 현장수령 무료 (배송 불가)

## 예매취소조건

※ 관람일 기준이 우선 적용됩니다.

| 취소 시점 | 취소수수료 |
| --- | --- |
| 예매 후 7일 이내 | 없음 |
| 예매 후 8일 ~ 관람 10일 전 | 장당 4,000원 (티켓금액의 10% 한도) |
| 관람일 9~7일 전 | 티켓금액의 10% |
| 관람일 6~3일 전 | 티켓금액의 20% |
| 관람일 2~1일 전 | 티켓금액의 30% |

※ 예매 당일 밤 12시 이전 취소 시 수수료 없음(예매수수료도 환불).

## 취소·환불 방법

- 마이페이지 > 예매내역 > 예매취소
- 관람일 1일 전까지 취소 가능, 공연 당일 취소·환불 불가
`;
}
